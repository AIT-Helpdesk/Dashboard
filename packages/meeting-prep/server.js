function buildReportComponent(kind, data) {
  const title = REPORT_TITLES[kind];
  if (!title) return null; // an unrecognised file in data/ -- skip it, don't fail the whole request over it
  const siteSlug = slugify(data.site || 'unknown');
  // Datto's reports all have a single createDate; Dark Web Monitoring has a
  // period range instead -- normalised to one display string here so every
  // component still has a createDate the card/detail header can show
  // without needing to know which shape produced it.
  const createDate = data.createDate || (data.periodStart && data.periodEnd ? `${data.periodStart} to ${data.periodEnd}` : null);
  const base = {
    id: `report-${kind}-${siteSlug}`,
    source: REPORT_SOURCES[kind] || 'Report',
    kind,
    title,
    // The real site name this component's own data came from (not the
    // search term that found it, which can be a wildcard matching more
    // than one client) -- lets the client group components by site, e.g.
    // for Selected Overview's own per-site tabs when a broad search
    // matched several clients at once.
    site: data.site || null,
    createDate,
    images: loadReportImages(kind, siteSlug),
    // The SharePoint webUrl of the original report PDF this component was
    // parsed from -- set on data/*.json by the parsing pipeline (see data/
    // README.md), null for anything parsed before this field existed.
    // Rendered by client.js's cardEl() as an "Original File" link at the
    // bottom of the card so a TAM can jump straight to the source document.
    sourceUrl: data.sourceUrl || null,
  };
  if (kind === 'executive-summary') {
    const summarySection = (data.sections || []).find((s) => s.kind === 'summary');
    return { ...base, stats: { overallScore: summarySection ? summarySection.overallScore : null }, sections: data.sections || [] };
  }
  if (kind === 'device-storage') {
    const drives = data.drives || [];
    return {
      ...base,
      stats: { driveCount: drives.length, criticalCount: drives.filter((d) => d.usedPercent != null && d.usedPercent >= 90).length },
      drives,
    };
  }
  if (kind === 'patch-management-summary') {
    const summary = data.summary || {};
    return {
      ...base,
      stats: { fullyPatched: summary['Fully Patched'] || 0, total: Object.values(summary).reduce((sum, n) => sum + (n || 0), 0) },
      summary,
      devices: data.devices || [],
    };
  }
  if (kind === 'device-health-summary') {
    const summary = data.summary || {};
    return { ...base, stats: { checksPassed: summary.checksPassed, checksFailed: summary.checksFailed }, summary, devices: data.devices || [] };
  }
  if (kind === 'hardware-lifecycle') {
    const bands = data.bands || [];
    const countOf = (id) => (bands.find((b) => b.id === id) || { devices: [] }).devices.length;
    return {
      ...base,
      stats: { within12: countOf('within-12-months'), months12to24: countOf('12-24-months'), plus24: countOf('24-plus-months') },
      summary: data.summary || {},
      bands,
    };
  }
  if (kind === 'network-audit') {
    return { ...base, stats: { managedCount: data.managedCount || 0, unmanagedCount: data.unmanagedCount || 0 }, devices: data.devices || [] };
  }
  if (kind === 'open-monitor-alerts') {
    const devices = data.devices || [];
    return {
      ...base,
      stats: { totalOpen: devices.reduce((n, d) => n + (d.total || 0), 0), devicesWithAlerts: devices.filter((d) => (d.total || 0) > 0).length },
      devices,
    };
  }
  // Device Activity, Device Monitor Status, Software, and the two Patch
  // Management event-log reports all carry a huge amount of per-device
  // detail in the source PDF (a month of activity events, a live monitor
  // reading per device, every installed software version per device, a
  // patch-by-patch table per device) -- by request, these only get a
  // `summary` (counts) here, not the full per-device breakdown, so a
  // client with many devices doesn't blow this up into an unreadable
  // card. The counts themselves are computed once, at parse time, and
  // stored directly in data/*.json's own `summary` -- this just passes
  // them through.
  if (kind === 'device-activity') {
    return { ...base, stats: { failedEvents: (data.summary || {}).failedEvents || 0 }, summary: data.summary || {} };
  }
  if (kind === 'device-monitor-status') {
    return { ...base, stats: { totalMonitorEntries: (data.summary || {}).totalMonitorEntries || 0 }, summary: data.summary || {} };
  }
  if (kind === 'software') {
    return { ...base, stats: { distinctTitles: (data.summary || {}).distinctTitles || 0 }, summary: data.summary || {} };
  }
  if (kind === 'patch-management-activity') {
    return { ...base, stats: { totalPatchInstallEvents: (data.summary || {}).totalPatchInstallEvents || 0 }, summary: data.summary || {} };
  }
  if (kind === 'patch-management-details') {
    return { ...base, stats: { totalPatchesListed: (data.summary || {}).totalPatchesListed || 0 }, summary: data.summary || {} };
  }
  if (kind === 'dark-web-monitoring') {
    const summary = data.summary || {};
    return {
      ...base,
      stats: { totalCompromises: summary.totalCompromises || 0, customerAverage: (data.benchmark || {}).customerAverageCompromises || 0 },
      summary,
      benchmark: data.benchmark || {},
      monitoring: data.monitoring || {},
      organizationalCompromises: data.organizationalCompromises || [],
      breaches: data.breaches || { totalCompromises: 0, breaches: [] },
    };
  }
  return null;
}

// data/<client-slug>/<date>/<kind>.json -- one folder per client, one
// dated subfolder per report run, mirroring the SharePoint Processed
// folder's own <Client Name>/<date>/ shape 1:1 (by request, so the two
// stay easy to reason about together). Replaced the original flat
// data/<slug>--<kind>.json (silently overwritten on every re-run) once
// keeping history actually mattered -- see data/README.md. `images/`
// lives alongside the client folders in this same directory (its own
// unrelated flat naming scheme, untouched by this) -- skipped here by
// name, not by "is it a real client", since a client could in principle
// be named something that only coincidentally isn't "images".
function loadFileReportComponents(siteTerm) {
  let clientDirs;
  try {
    clientDirs = fs
      .readdirSync(REPORT_DATA_DIR, { withFileTypes: true })
      .filter((d) => d.isDirectory() && d.name !== 'images');
  } catch {
    return []; // data/ doesn't exist yet on a fresh checkout -- no report components, not an error
  }
  const components = [];
  for (const clientDir of clientDirs) {
    const clientPath = path.join(REPORT_DATA_DIR, clientDir.name);
    let dateDirs;
    try {
      dateDirs = fs.readdirSync(clientPath, { withFileTypes: true }).filter((d) => d.isDirectory());
    } catch {
      continue;
    }
    // Newest date first (plain string sort works here since the folder
    // name is always YYYY-MM-DD) -- the first time a given `kind` shows
    // up below is therefore always its most recent run, so only ONE
    // snapshot per kind ever becomes a component. Older dates stay on
    // disk for history, just not surfaced on this page (yet -- see the
    // README's own "Not yet built" for a future trend-over-time view).
    dateDirs.sort((a, b) => b.name.localeCompare(a.name));
    const seenKinds = new Set();
    for (const dateDir of dateDirs) {
      const datePath = path.join(clientPath, dateDir.name);
      let filenames;
      try {
        filenames = fs.readdirSync(datePath).filter((f) => f.endsWith('.json'));
      } catch {
        continue;
      }
      for (const filename of filenames) {
        const kind = filename.replace(/\.json$/, '');
        if (seenKinds.has(kind)) continue; // already have this kind's LATEST run from a newer date folder
        let data;
        try {
          data = JSON.parse(fs.readFileSync(path.join(datePath, filename), 'utf8'));
        } catch (err) {
          console.error(`Meeting Prep: failed to read data/${clientDir.name}/${dateDir.name}/${filename}:`, err.message);
          continue;
        }
        // Marked seen regardless of whether it matches the search below --
        // every file under one client folder describes that SAME client,
        // so if its newest run doesn't match the search term, no older
        // run of the same kind should surface either.
        seenKinds.add(kind);
        if (!data.site || !matchesWildcard(data.site, siteTerm)) continue;
        const component = buildReportComponent(kind, data);
        if (component) components.push(component);
      }
    }
  }
  components.sort((a, b) => REPORT_ORDER.indexOf(a.kind) - REPORT_ORDER.indexOf(b.kind));
  return components;
}

// Same walk as loadFileReportComponents() above, but for EVERY client
// folder at once and with no site-name filter -- used by Service Actions
// (a separate page) to run the recommendations engine across the whole
// client base in one request. Kept here rather than duplicated because
// it's the exact same "latest date wins per kind" logic, just without the
// matchesWildcard() narrowing loadFileReportComponents() applies. Returns
// one entry per client folder that has at least one component, `site`
// taken from whichever file supplied it (they're expected to agree within
// one client folder -- see data/README.md's own note on this) falling
// back to a prettified version of the folder name on the rare chance no
// file inside it has a `site` field at all.
function loadAllFileReportComponentsByClient() {
  let clientDirs;
  try {
    clientDirs = fs
      .readdirSync(REPORT_DATA_DIR, { withFileTypes: true })
      .filter((d) => d.isDirectory() && d.name !== 'images');
  } catch {
    return [];
  }
  const results = [];
  for (const clientDir of clientDirs) {
    const clientPath = path.join(REPORT_DATA_DIR, clientDir.name);
    let dateDirs;
    try {
      dateDirs = fs.readdirSync(clientPath, { withFileTypes: true }).filter((d) => d.isDirectory());
    } catch {
      continue;
    }
    dateDirs.sort((a, b) => b.name.localeCompare(a.name));
    const seenKinds = new Set();
    const components = [];
    let site = null;
    for (const dateDir of dateDirs) {
      const datePath = path.join(clientPath, dateDir.name);
      let filenames;
      try {
        filenames = fs.readdirSync(datePath).filter((f) => f.endsWith('.json'));
      } catch {
        continue;
      }
      for (const filename of filenames) {
        const kind = filename.replace(/\.json$/, '');
        if (seenKinds.has(kind)) continue;
        let data;
        try {
          data = JSON.parse(fs.readFileSync(path.join(datePath, filename), 'utf8'));
        } catch (err) {
          console.error(`Meeting Prep: failed to read data/${clientDir.name}/${dateDir.name}/${filename}:`, err.message);
          continue;
        }
        seenKinds.add(kind);
        if (!site && data.site) site = data.site;
        const component = buildReportComponent(kind, data);
        if (component) components.push(component);
      }
    }
    if (components.length === 0) continue;
    components.sort((a, b) => REPORT_ORDER.indexOf(a.kind) - REPORT_ORDER.indexOf(b.kind));
    results.push({
      client: site || clientDir.name.replace(/-/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase()),
      components,
    });
  }
  results.sort((a, b) => a.client.localeCompare(b.client));
  return results;
}


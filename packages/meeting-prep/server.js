// Meeting Prep -- pulls every "reportable" chunk of data for one client
// into independent, selectable components, so a TAM can pick which ones
// to actually bring into a client meeting. Deliberately NOT built on or
// inside Check Client -- by request, Check Client is a reconciliation/
// consolidation tool (fixed sections, always shows everything for that
// client at once); this page is about curating a subset to present, which
// is a genuinely different job even though both are "look up one client
// across several systems."
//
// Two kinds of source feed the same generic `components` array (each
// entry carrying its own `kind`, see the client for how that's rendered):
// file-based report components (below), parsed from report PDFs each
// system's own scheduler/export produces (see the parser this data/
// folder's own README links to) into one JSON file per report per site,
// dropped into data/ using the naming convention documented there; and a
// couple of live sources -- Datto RMM devices and Autotask ticket counts,
// see "Live components" further down -- fetched fresh (Datto cached 20
// min, same convention as this dashboard's other Datto pulls) on every
// search. An earlier version of this page had a live Datto devices/alerts
// source in the old plain-table shape; that was removed by request, then
// Datto devices were reintroduced here in a new widget shape (by request,
// "like you previously did but as widgets"). More systems get added here
// the same way Dark Web Monitoring just was -- a new REPORT_TITLES/
// REPORT_SOURCES/REPORT_ORDER entry plus a new buildReportComponent()
// branch for a file-based one, or a new builder function pushed into the
// live half of the /components route below for anything live.

// A stable, URL/DOM-safe id for a report component -- real site names can
// contain spaces/punctuation, so this isn't just the raw name.
// Deterministic from the site name alone, so the same site always gets
// the same component id across searches/refreshes -- that's what lets the
// client keep a checkbox's "selected" state matched to the right
// component after a re-fetch.
const { slugify } = require('./slug.js');


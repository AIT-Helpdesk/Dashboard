// Live components -- fetched fresh from each system's own API on every
// search, rather than read from data/. Each builder below is wrapped
// individually in the /components route (Promise.all + its own try/catch),
// same "one broken card doesn't take down the others" reasoning
// datto-rmm/lib.js's own getOverview() already uses for its filter cards --
// a Datto outage shouldn't hide the file-based reports, and vice versa.

// Datto RMM devices, as widgets -- by request ("From Datto RMM like you
// previously did but as widgets like this"), reusing Check Client's own
// Section 5 pattern (own 20-minute in-process cache via getAllDevices(),
// matched against Datto's own siteName with matchesWildcard()) rather than
// calling datto-rmm/server.js (that package's own router/cache is for its
// account-wide overview page, a different shape -- see check-client's own
// comment on this same choice).
const DATTO_CACHE_TTL_MS = 20 * 60 * 1000; // 20 min -- same convention as Datto RMM's own overview cache and Check Client's Section 5
let dattoDevicesCache = null; // { data, expiresAt }
let dattoDevicesInFlight = null;
async function getCachedDattoDevices(force) {
  if (!force && dattoDevicesCache && Date.now() < dattoDevicesCache.expiresAt) return dattoDevicesCache.data;
  if (!dattoDevicesInFlight) {
    dattoDevicesInFlight = dattoRmm
      .getAllDevices()
      .then((data) => {
        dattoDevicesCache = { data, expiresAt: Date.now() + DATTO_CACHE_TTL_MS };
        return data;
      })
      .finally(() => {
        dattoDevicesInFlight = null;
      });
  }
  return dattoDevicesInFlight;
}

// "Seen <7 days" / "7-30 days" / "not seen 30+ days" -- the same 3-band
// check-in-freshness read the screenshot's KPI tiles and segmented bar both
// use. `lastSeen` missing entirely (never confirmed against a real payload
// to be impossible, just not seen in testing) gets its own 'unknown' bucket
// rather than being silently folded into "stale" -- a device Datto has
// simply never reported a lastSeen for isn't the same claim as "not seen in
// 30+ days".
function classifyFreshness(lastSeenIso) {
  if (!lastSeenIso) return 'unknown';
  const ageDays = (Date.now() - new Date(lastSeenIso).getTime()) / 86400000;
  if (!Number.isFinite(ageDays)) return 'unknown';
  if (ageDays < 7) return 'recent';
  if (ageDays < 30) return 'ageing';
  return 'stale';
}

function buildDattoLiveDevicesComponent(siteTerm, allDevices, asOf) {
  const devices = allDevices.filter((d) => matchesWildcard(d.site, siteTerm));
  // No matching devices -- omit the card entirely rather than show an
  // empty one, same convention loadFileReportComponents() already follows
  // for a site with no report files.
  if (devices.length === 0) return null;

  const buckets = { recent: 0, ageing: 0, stale: 0, unknown: 0 };
  const byType = new Map();
  const rows = [];
  for (const d of devices) {
    const freshness = classifyFreshness(d.lastSeen);
    buckets[freshness] += 1;
    const type = d.deviceType || 'Unknown';
    byType.set(type, (byType.get(type) || 0) + 1);
    rows.push({
      id: d.id,
      hostname: d.hostname,
      type,
      lastSeen: d.lastSeen,
      freshness,
      online: d.online,
      lastUser: d.lastUser,
    });
  }
  rows.sort((a, b) => (a.hostname || '').localeCompare(b.hostname || ''));

  // "Core Resources" was hardcoded as a literal title at first (lifted
  // straight from the reference screenshot's own dashboard heading, which
  // -- as it turns out -- was itself a real client's own Datto dashboard,
  // not a generic mockup) -- a real bug, confirmed by request ("Datto RMM
  // tile is called Core Resources regardless of the chosen and reported
  // client"): every client's card read identically, which is actively
  // confusing when switching between clients in one session.
  //
  // First attempted fix got this WRONG in a worse way: it kept the literal
  // "Core Resources" text and just appended the real site name after it
  // (`Core Resources -- ${siteNames[0]}`), so a search for e.g. "Flow
  // Financial Planning" rendered the title "Core Resources -- Flow
  // Financial Planning" -- confirmed by a screenshot Amber sent showing
  // exactly that, on a real client that is NOT called Core Resources. That
  // read as two different clients' data being mixed together on one card,
  // which is a much worse failure mode than the original bug (a static
  // wrong label) even though no data was actually wrong underneath it --
  // this was purely a display string mistake, but a bad one to make on a
  // page used live in front of clients. Correct fix: the hardcoded string
  // is gone entirely, the title is ONLY the real matched site name(s) --
  // Datto's own siteName off the matched devices themselves, not the raw
  // siteTerm search text (which can be a wildcard like "Kraftur*" rather
  // than a clean name). Normally every matched device agrees on one real
  // site name; the rare case where a broad wildcard spans more than one is
  // called out explicitly rather than just picking one and hiding the
  // ambiguity.
  const siteNames = [...new Set(devices.map((d) => d.site).filter(Boolean))];
  const title = siteNames.length === 1 ? siteNames[0] : siteNames.length > 1 ? `${siteNames.length} sites matched` : 'Live Devices';

  return {
    id: `live-datto-devices-${slugify(siteTerm)}`,
    source: 'Datto RMM (live)',
    kind: 'datto-live-devices',
    title,
    // null when this one component's own devices span more than one real
    // site (same ambiguous-wildcard case `title` above already calls out)
    // -- same reasoning as buildReportComponent()'s own `site` field, but
    // there's no single real value to give here in that case.
    site: siteNames.length === 1 ? siteNames[0] : null,
    createDate: asOf,
    images: [],
    stats: { total: devices.length, notSeenStale: buckets.stale },
    summary: {
      total: devices.length,
      seenRecent: buckets.recent,
      seenAgeing: buckets.ageing,
      notSeenStale: buckets.stale,
      unknown: buckets.unknown,
    },
    byType: [...byType.entries()].map(([type, count]) => ({ type, count })).sort((a, b) => b.count - a.count),
    // See datto-rmm/lib.js's own mapDeviceSummary() comment -- the
    // deviceType field this breakdown is built from hasn't been confirmed
    // against a real payload from this account yet. Carried through here so
    // the client can show an honest caveat next to the widget rather than
    // presenting it as settled.
    deviceTypeConfirmed: false,
    devices: rows,
  };
}

// Autotask ticket counts -- by request ("ticket counts by Priority, Open
// and closed in the month... just getting something in there, we will
// elaborate on this one later"), so deliberately minimal: current open
// tickets grouped by priority, plus how many were opened and closed in the
// current AEST calendar month. "Closed" reuses Completed Tickets' own
// confirmed real definition (status 5 "Complete" by completedDate, UNIONed
// with status 20 "Billing - Contract" by resolvedDateTime -- see that
// package's own server.js comment for why status 20 needs the different
// date field). "Opened" is simply createDate falling in the same month --
// not independently confirmed against any existing page since nothing else
// on this dashboard counts tickets opened-in-a-month, so treat that one
// figure as the more provisional of the two if it's ever checked against
// Autotask's own UI count. Monitoring-alert tickets (issueType 14) are
// excluded from every count here, same as everywhere else on this
// dashboard that counts tickets, and for the same confirmed reason
// (excludeMonitoringAlerts()'s own comment).
async function buildAutotaskTicketsComponent(client, siteTerm) {
  const resolved = await resolveSingleCompany(client, siteTerm, null);
  const base = {
    id: `live-autotask-tickets-${slugify(siteTerm)}`,
    source: 'Autotask (live)',
    kind: 'autotask-tickets',
    title: 'Ticket Summary',
    createDate: null,
    images: [],
  };
  if (resolved.status !== 'ok') {
    // Not folded silently into "no data" -- a client search term that
    // doesn't resolve to exactly one Autotask company is a real signal
    // worth surfacing (wrong/ambiguous search term), not a missing-config
    // state like Datto credentials being absent.
    return { ...base, stats: null, resolveStatus: resolved.status, matches: resolved.matches || [] };
  }
  const company = resolved.company;
  const companyID = company.id;

  const currentMonthKey = todayAestKey().slice(0, 7);
  const { windowStart, windowEnd } = monthKeysWindow([currentMonthKey]);

  const [openTicketsRaw, completedRaw, billingRaw, openedThisMonthRaw, priorityLabels] = await Promise.all([
    listAll(client.tickets, [
      { op: 'eq', field: 'companyID', value: companyID },
      { op: 'notExist', field: 'completedDate' },
    ]),
    listAll(client.tickets, [
      { op: 'eq', field: 'companyID', value: companyID },
      { op: 'eq', field: 'status', value: 5 },
      { op: 'gte', field: 'completedDate', value: windowStart },
      { op: 'lt', field: 'completedDate', value: windowEnd },
    ]),
    listAll(client.tickets, [
      { op: 'eq', field: 'companyID', value: companyID },
      { op: 'eq', field: 'status', value: 20 },
      { op: 'gte', field: 'resolvedDateTime', value: windowStart },
      { op: 'lt', field: 'resolvedDateTime', value: windowEnd },
    ]),
    listAll(client.tickets, [
      { op: 'eq', field: 'companyID', value: companyID },
      { op: 'gte', field: 'createDate', value: windowStart },
      { op: 'lt', field: 'createDate', value: windowEnd },
    ]),
    getPicklistLabels(client.tickets, 'priority'),
  ]);

  const openTickets = excludeMonitoringAlerts(openTicketsRaw);
  const closedThisMonth = excludeMonitoringAlerts([...completedRaw, ...billingRaw]);
  const openedThisMonth = excludeMonitoringAlerts(openedThisMonthRaw);

  const byPriorityMap = new Map();
  for (const t of openTickets) {
    const label = priorityLabels.get(t.priority) || `Priority ${t.priority}`;
    byPriorityMap.set(label, (byPriorityMap.get(label) || 0) + 1);
  }

  return {
    ...base,
    resolveStatus: 'ok',
    companyName: company.companyName,
    monthLabel: monthLabel(currentMonthKey),
    stats: { openCount: openTickets.length, openedThisMonth: openedThisMonth.length, closedThisMonth: closedThisMonth.length },
    byPriority: [...byPriorityMap.entries()].map(([label, count]) => ({ label, count })).sort((a, b) => b.count - a.count),
  };
}


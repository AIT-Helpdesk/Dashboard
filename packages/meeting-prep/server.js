// File-based report components -- Datto RMM's own Report Center/Analytics
// has no REST API at all (confirmed against Datto's own docs), so these
// come from a different pipeline entirely: report PDFs generated by the
// account's existing Report Scheduler get parsed (see the parser this
// data/ folder's own README links to) into one JSON file per report per
// site, dropped in data/ using the naming convention documented there.
// This route just reads whatever's in data/ on every request -- it's a
// handful of small local JSON files, not worth caching -- and turns each
// one whose "site" field matches the search into a component, same shape
// as the live Datto RMM ones above. This data/ folder is also the exact
// place any future automated pickup (see data/README.md) writes into, so
// there's nothing here that needs reworking once that lands -- it just
// means files start showing up on their own instead of by hand.
const REPORT_DATA_DIR = path.join(__dirname, 'data');
const REPORT_IMAGES_DIR = path.join(__dirname, 'data', 'images');

// Exact, unaltered crops of the source report PDF -- pixels straight out of
// the PDF at 200dpi, no re-rendering, no re-interpretation -- alongside the
// structured data above, by request ("would it be possible to just give me
// each section of the reports in their exact format as they are without
// changing them"). Executive Summary has real named sub-sections in Datto's
// own layout (Summary, Asset Management, etc. -- see EXEC_SUMMARY_IMAGE_ORDER
// below), so it gets one image per section, including one stitched from two
// page crops where a section straddles a page break (Asset Management does,
// on the Kraftur sample). The other 4 report types have no sub-sections
// smaller than the whole report in Datto's layout, so they get one image per
// content page instead (cover page excluded). Filenames follow the same
// `<site-slug>--<kind>--...` convention as data/*.json, just with a third
// segment identifying the section/page -- see data/README.md.
const EXEC_SUMMARY_IMAGE_ORDER = ['summary', 'asset-management', 'patch-management', 'software-management', 'antivirus'];

function loadReportImages(kind, siteSlug) {
  const prefix = `${siteSlug}--${kind}--`;
  let filenames;
  try {
    filenames = fs.readdirSync(REPORT_IMAGES_DIR).filter((f) => f.startsWith(prefix) && f.endsWith('.png'));
  } catch {
    return []; // data/images/ doesn't exist yet, or nothing generated for this report -- no images, not an error
  }
  const entries = filenames.map((filename) => ({ id: filename.slice(prefix.length, -'.png'.length), filename }));
  if (kind === 'executive-summary') {
    entries.sort((a, b) => EXEC_SUMMARY_IMAGE_ORDER.indexOf(a.id) - EXEC_SUMMARY_IMAGE_ORDER.indexOf(b.id));
  } else {
    // "page-2", "page-3", ... -- sort numerically, not lexically (page-10
    // would otherwise sort before page-2).
    entries.sort((a, b) => (parseInt((a.id.match(/\d+/) || [0])[0], 10) || 0) - (parseInt((b.id.match(/\d+/) || [0])[0], 10) || 0));
  }
  return entries.map((e) => ({ id: e.id, url: `/api/meeting-prep/images/${e.filename}` }));
}


// A caught/rejected promise already can't take the whole response down --
// every live source below is wrapped in its own try/catch. But a live
// source that's gone SLOW instead of failing outright (stuck retrying
// against a rate limit, a network stall, whatever) is a sharper risk:
// `await` just waits, so a live source that never settles at all would
// hold up the entire response indefinitely -- including the file-based
// report components above, which are already read from disk and sitting
// ready to send well before any live source is even called. That's what a
// real incident traced back to here: repeated Autotask 429s with nothing
// bounding how long the underlying client's retry might take (see
// data/README.md's neighbouring note, or ask Amber/Claude for the
// incident writeup) turned one rate-limited ticket query into the whole
// page looking like it had silently lost every report. Every live source
// gets a hard timeout for exactly this reason -- not just the one that's
// already caused a problem, since a slow Datto RMM call deserves the same
// guarantee for the same reason: nothing live is allowed to block data
// that was never dependent on it in the first place.
const LIVE_SOURCE_TIMEOUT_MS = 8000;
function withTimeout(promise, label) {
  let timer;
  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => reject(new Error(`${label} timed out after ${LIVE_SOURCE_TIMEOUT_MS}ms`)), LIVE_SOURCE_TIMEOUT_MS);
  });
  return Promise.race([promise, timeout]).finally(() => clearTimeout(timer));
}

// One route, returning a generic `components` array (each with its own
// `kind`) rather than separate per-source endpoints -- deliberately, so
// adding a second source later means pushing more entries into the same
// array/shape, not a client-side rewrite.
router.get('/components', async (req, res) => {
  // This endpoint's whole point is live/current data (device check-ins,
  // ticket counts, whatever's newest in data/) -- explicitly uncacheable,
  // so a browser never serves a stale response for a repeated search
  // instead of hitting the network again. Belt-and-braces with the
  // matching `cache: 'no-store'` on the client's own fetch() call.
  res.set('Cache-Control', 'no-store');
  const siteTerm = (req.query.client || '').trim();
  if (!siteTerm) return res.status(400).json({ error: 'Query param "client" is required.' });
  try {
    const asOf = new Date().toISOString();
    // File-based report components are read from disk synchronously, right
    // here, before any live source is even touched -- nothing below this
    // line can ever prevent these from being computed. withTimeout() above
    // is what guarantees they also can't be prevented from being SENT.
    const components = loadFileReportComponents(siteTerm);

    // TEMPORARILY DISABLED (2026-09-23): the live Autotask ticket-counts
    // component was hitting Autotask's own API rate limit (repeated 429s
    // logged at the exact point a client-facing incident was reported).
    // Pulled out as an immediate stabilisation; re-enable (wrapped in
    // withTimeout(), same as Datto below) only after confirming with
    // Autotask why 5 parallel ticket queries per search are enough to trip
    // a 429 -- a per-account limit shared with every other page on this
    // dashboard, not something this route can just retry its way past.
    const dattoComponent = await (async () => {
      if (!dattoRmm.hasDattoCredentials()) return null;
      try {
        const allDevices = await withTimeout(getCachedDattoDevices(req.query.refresh === 'true'), 'Datto RMM devices');
        return buildDattoLiveDevicesComponent(siteTerm, allDevices, asOf);
      } catch (err) {
        console.error('Meeting Prep: Datto RMM live devices failed:', err.message);
        return null;
      }
    })();
    if (dattoComponent) components.push(dattoComponent);
    // const ticketsComponent = ... -- see comment above; disabled for now.

    res.json({ connected: true, asOf, siteTerm, components });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: err.message });
  }
});

